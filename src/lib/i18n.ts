export const messages: Record<Lang, Record<MessageKey, string>> = { en, sv };

export type Vars = Record<string, string | number>;

export function t(lang: Lang, key: MessageKey, vars?: Vars): string {
  const template = messages[lang][key] ?? messages.en[key];
  return vars ? template.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`)) : template;
}
