// English is the default language; Swedish is opt-in through the dd_lang cookie.
export type Lang = "en" | "sv";
export const LANG_COOKIE = "dd_lang";
export const LANGS: readonly Lang[] = ["en", "sv"];

export function parseLang(value?: string | null): Lang {
  return value === "sv" ? "sv" : "en";
}

export function langFromCookieHeader(header: string | null): Lang {
  const match = header?.match(new RegExp(`(?:^|;\\s*)${LANG_COOKIE}=([^;]*)`));
  return parseLang(match?.[1]);
}

export function langFromRequest(request: Request): Lang {
  return langFromCookieHeader(request.headers.get("cookie"));
}

export function dateLocale(lang: Lang) {
  return lang === "sv" ? "sv-SE" : "en";
}

